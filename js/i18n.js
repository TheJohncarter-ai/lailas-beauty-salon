/* ---------- runtime ---------- */
(() => {
  const KEY = 'laila_lang';
  const captured = {};    // el español capturado del DOM en la primera pasada
  const capturedPh = {};
  const capturedAl = {};
  const listeners = [];

  // El sitio es en español. Punto. El inglés existe solo para el turismo de
  // la costa y NUNCA se activa solo: hay que tocar el botón EN. Detectar el
  // idioma del navegador le servía inglés a Googlebot, que se presenta como
  // en-US, así que el español nunca se indexaba.
  const detect = () => {
    try { const s = localStorage.getItem(KEY); if (s === 'en' || s === 'es') return s; } catch (_) {}
    return 'es';
  };

  let lang = detect();

  const t = key => (lang === 'en'
    ? (window.I18N_EN[key] ?? captured[key])
    : (captured[key] ?? window.I18N_ES[key] ?? window.I18N_EN[key])) ?? '';

  const apply = () => {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const k = el.dataset.i18n;
      if (!(k in captured)) captured[k] = el.innerHTML;
      const v = lang === 'en' ? window.I18N_EN[k] : captured[k];
      if (v != null && el.innerHTML !== v) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const k = el.dataset.i18nPh;
      if (!(k in capturedPh)) capturedPh[k] = el.placeholder;
      const v = lang === 'en' ? window.I18N_EN[k] : capturedPh[k];
      if (v != null) el.placeholder = v;
    });
    document.querySelectorAll('[data-i18n-al]').forEach(el => {
      const k = el.dataset.i18nAl;
      if (!(k in capturedAl)) capturedAl[k] = el.getAttribute('aria-label');
      const v = lang === 'en' ? window.I18N_EN[k] : capturedAl[k];
      if (v != null) el.setAttribute('aria-label', v);
    });
    document.documentElement.lang = lang === 'en' ? 'en' : 'es-HN';
    if (lang === 'en') {
      document.title = window.I18N_EN['js.title'];
      const md = document.querySelector('meta[name="description"]');
      if (md) md.content = window.I18N_EN['js.desc'];
    }
    document.querySelectorAll('.lang__btn').forEach(b => {
      const on = b.dataset.lang === lang;
      b.classList.toggle('is-active', on);
      b.setAttribute('aria-pressed', String(on));
    });
    listeners.forEach(fn => fn(lang));
  };

  const set = l => {
    if (l !== 'en' && l !== 'es') return;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch (_) {}
    apply();
  };

  document.addEventListener('click', e => {
    const b = e.target.closest('.lang__btn');
    if (b) set(b.dataset.lang);
  });

  window.LB_I18N = { get lang() { return lang; }, t, set, apply, onChange: fn => listeners.push(fn) };

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', apply);
  else apply();
})();
